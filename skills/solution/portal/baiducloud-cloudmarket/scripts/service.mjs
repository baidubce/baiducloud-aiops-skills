const _agentCache = new Map();
async function getDispatcher(urlStr) {
  const ca = process.env.TOKEN_STORE_CA_BUNDLE;
  let extraTls = null;
  if (ca) {
    extraTls = { ca: fs.readFileSync(ca) };
  }
  if (!extraTls) {
    return null;
  }
  const key = extraTls.ca ? `ca:${extraTls.ca.length}` : `insecure:${extraTls.rejectUnauthorized}`;
  if (!_agentCache.has(key)) {
    const { Agent } = await import('undici'); // Node18+ 内建，非第三方
    _agentCache.set(key, new Agent({ connect: extraTls }));
  }
  return _agentCache.get(key);
}

async function fetchWithTimeout(urlStr, opts = {}, timeoutMs = 15000) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeoutMs);
  try {
    const dispatcher = await getDispatcher(urlStr);
    return await fetch(urlStr, { ...opts, ...(dispatcher ? { dispatcher } : {}), signal: controller.signal });
  } finally {
    clearTimeout(timer);
  }
}

async function postForm(urlStr, form, timeoutMs = 15000) {
  const resp = await fetchWithTimeout(
    urlStr,
    {
      method: 'POST',
      headers: { 'Content-Type': 'application/x-www-form-urlencoded', Accept: 'application/json' },
      body: new URLSearchParams(form).toString(),
    },
    timeoutMs,
  );
  const text = await resp.text();
  if (!resp.ok) {
    const e = new Error(`HTTP ${resp.status}`);
    e.status = resp.status;
    e.body = text;
    throw e;
  }
  return text ? JSON.parse(text) : {};
}

