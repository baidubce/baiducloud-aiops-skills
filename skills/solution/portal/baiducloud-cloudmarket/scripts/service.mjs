// 发起一次浏览器登录，成功后把 token 原子写入对应 env 的 token 文件。
// opts.open=false 时只产出授权链接不自动打开；opts.onPrompt 回调用于把链接/
// 提示交给客户层打印（服务层不直接写 stdout，日志走 console.error）。
export async function login({
  env = IAM_ENV,
  open = true,
  timeoutMs = 600000,
  onPrompt,
  accountId = null,
  force = false,
  port = 0,
} = {}) {
  if (env !== 'prod') { throw new Error(`正式包仅支持 --env prod，收到：${env}`); }
  // 免登判断：refresh_token 未过期，且（若指定）登录人与期望 account_id 一致 → 直接复用。
  // force=true 时跳过免登（供"登录态失效自动重登"场景：此时本地 token 可能看似
  // 未过期但已被服务端拒绝，必须真正重新走一次授权，否则无法恢复）。
  if (!force) {
    const plan = resolveLoginPlan(env, accountId);
    if (plan.action === 'skip') {
      return {
        env,
        account_id: plan.identity.account_id,
        username: plan.identity.username,
        token_file: tokenFilePath(env),
        refresh_token_expires_at: plan.record.refresh_token_expires_at,
        skipped: true,
        reason: plan.reason,
      };
    }
    if (plan.action === 'promote') {
      persistLoginRecord(env, plan.record); // 把该账号归档凭证提升为 active（切账号免浏览器）
      return {
        env,
        account_id: plan.identity.account_id,
        username: plan.identity.username,
        token_file: tokenFilePath(env),
        refresh_token_expires_at: plan.record.refresh_token_expires_at,
        skipped: true,
        reason: 'switched',
      };
    }
  }
  const base = resolveIamBaseFor(env);
  if (!base) {
    throw new LoginRequiredError(`缺少 IAM 域名配置：请设置 IAM_PUBLIC_BASE_${env.toUpperCase()} 或 IAM_PUBLIC_BASE`);
  }
  const clientId = resolveClientIdFor(env);
  const state = b64urlNoPad(crypto.randomBytes(48));
  const nonce = b64urlNoPad(crypto.randomBytes(48));
  const { verifier, challenge } = genPkce();

  // 先起本地回调服务器拿随机端口
  // 回调服务器：默认随机端口；指定 port 便于 SSH 隧道/远端登录（需与转发端口一致）。
  const server = http.createServer();
  await new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(port || 0, '127.0.0.1', () => resolve());
  });
  const boundPort = server.address().port;
  const redirectUri = `http://127.0.0.1:${boundPort}/callback`;

  const callbackPromise = new Promise((resolve) => {
    const timer = setTimeout(() => {
      server.close();
      resolve(null);
    }, timeoutMs);
    server.on('request', (req, res) => {
      const u = new URL(req.url, 'http://127.0.0.1');
      if (u.pathname !== '/callback') {
        res.writeHead(404).end();
        return;
      }
      const code = u.searchParams.get('code');
      const st = u.searchParams.get('state');
      const error = u.searchParams.get('error');
      let result;
      let body;
      if (error) {
        result = { error };
        body = `登录失败：${error}，请关闭此页面重试。`;
      } else if (!code || !st || st !== state) {
        result = { error: 'state_mismatch_or_missing_code' };
        body = '登录回调校验失败，请关闭此页面重试。';
      } else {
        result = { code };
        body = '登录成功，可以关闭此页面并返回终端。';
      }
      res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' });
      res.end(`<html><body><h3>${body}</h3></body></html>`);
      clearTimeout(timer);
      server.close();
      resolve(result);
    });
  });

  const authUrl =
    `${base}${OAUTH_PATH_PREFIX}/authorize?` +
    new URLSearchParams({
      response_type: 'code',
      client_id: clientId,
      redirect_uri: redirectUri,
      scope: 'openid bce_sts offline_access',
      state,
      code_challenge: challenge,
      code_challenge_method: 'S256',
      nonce,
    }).toString();

  const opened = open ? openBrowser(authUrl) : false;
  if (typeof onPrompt === 'function') {
    onPrompt({ authUrl, opened, env, clientId });
  }

  const result = await callbackPromise;
  if (!result) {
    throw new LoginRequiredError('超时未收到浏览器回调，登录失败');
  }
  if (result.error) {
    throw new LoginRequiredError(`登录失败：${result.error}`);
  }

  let tokenResp;
  try {
    tokenResp = await postForm(`${base}${OAUTH_PATH_PREFIX}/token`, {
      grant_type: 'authorization_code',
      client_id: clientId,
      code: result.code,
      redirect_uri: redirectUri,
      code_verifier: verifier,
    });
  } catch (e) {
    throw new LoginRequiredError(`Token 交换失败：${e.message} ${e.body || ''}`);
  }
  if (!tokenResp.id_token || !tokenResp.refresh_token) {
    throw new LoginRequiredError('Token 响应缺少必要字段（id_token/refresh_token）');
  }

  const now = Date.now() / 1000;
  const claims = decodeJwtPayload(tokenResp.id_token) || {};
  const record = {
    env,
    account_id: claims.account_id ?? null,
    username: claims.username ?? null,
    id_token: tokenResp.id_token,
    id_token_expires_at: now + Number(tokenResp.expires_in ?? DEFAULT_ID_TTL),
    refresh_token: tokenResp.refresh_token,
    refresh_token_expires_at: now + Number(tokenResp.refresh_expires_in ?? DEFAULT_REFRESH_TTL),
    scope: tokenResp.scope || '',
    updated_at: now,
  };
  const file = tokenFilePath(env);
  persistLoginRecord(env, record); // 多账号安全：归档旧账号 + 写本账号归档 + 设为 active
  recordLoginMetric(record.account_id); // 度量：仅真正新登录计入当日登录账户（去重）
  // 返回不含任何凭证，只回环境/文件/过期时间/登录人
  return {
    env,
    client_id: clientId,
    account_id: record.account_id,
    username: record.username,
    token_file: file,
    id_token_expires_at: record.id_token_expires_at,
    refresh_token_expires_at: record.refresh_token_expires_at,
  };
}

// ── STS 临时凭证 ────────────────────────────────────────────────────────────
let stsCache = { access_key_id: null, secret_access_key: null, session_token: null, user_id: null, expiration_ts: 0 };
let stsInFlight = null;

async function refreshIdToken(tokens) {
  const now = Date.now() / 1000;
  if ((tokens.refresh_token_expires_at || 0) <= now) {
    throw new CliTokenExpiredError(loginGuide());
  }
  let resp;
  try {
    resp = await postForm(`${cfg.iamPublicBase}${OAUTH_PATH_PREFIX}/token`, {
      grant_type: 'refresh_token',
      client_id: cfg.clientId,
      refresh_token: tokens.refresh_token,
    });
  } catch (e) {
    throw new CliTokenExpiredError(`刷新 id_token 失败（${e.message}）：${e.body || ''}。请重新登录`);
  }
  const claims = decodeJwtPayload(resp.id_token) || {};
  const t = {
    env: IAM_ENV,
    account_id: claims.account_id ?? null,
    username: claims.username ?? null,
    id_token: resp.id_token,
    id_token_expires_at: now + Number(resp.expires_in ?? DEFAULT_ID_TTL),
    refresh_token: resp.refresh_token,
    refresh_token_expires_at: now + Number(resp.refresh_expires_in ?? DEFAULT_REFRESH_TTL),
    scope: resp.scope || '',
    updated_at: now,
  };
  persistLoginRecord(IAM_ENV, t); // 刷新也走多账号安全写入，保持 active 与归档一致
  log('id_token refreshed');
  return t;
}

async function requestSts(idToken) {
  const resp = await fetchWithTimeout(
    `${cfg.stsBase}/sessionToken/idToken?durationSeconds=3600`,
    {
      method: 'POST',
      headers: { Authorization: `Bearer ${idToken}`, 'Content-Type': 'application/json', Accept: 'application/json' },
    },
    15000,
  );
  const text = await resp.text();
  if (!resp.ok) {
    throw new Error(`STS 换取临时凭证失败（HTTP ${resp.status}）：${text}`);
  }
  return JSON.parse(text);
}

async function getSts() {
  const now = Date.now() / 1000;
  if (stsCache.expiration_ts - now > STS_MARGIN) {
    return { ...stsCache };
  }
  if (stsInFlight) {
    return stsInFlight;
  }
  stsInFlight = (async () => {
    if (!cfg.iamPublicBase || !cfg.stsBase) {
      throw new Error('缺少 IAM_PUBLIC_BASE / STS_BASE 配置');
    }
    let tokens;
    try {
      tokens = loadTokens();
    } catch (e) {
      throw new CliTokenExpiredError(`凭证不可读：${e.message}，请重新登录`);
    }
    if ((tokens.id_token_expires_at || 0) - now <= STS_MARGIN) {
      tokens = await refreshIdToken(tokens);
    }
    const r = await requestSts(tokens.id_token);
    stsCache = {
      access_key_id: r.accessKeyId,
      secret_access_key: r.secretAccessKey,
      session_token: r.sessionToken,
      user_id: r.userId,
      expiration_ts: Date.parse(r.expiration) / 1000,
    };
    log('STS credentials refreshed, expiration=', r.expiration);
    return { ...stsCache };
  })();
  try {
    return await stsInFlight;
  } finally {
    stsInFlight = null;
  }
}

// ── bce-auth-v1 签名 ────────────────────────────────────────────────────────
function uriEncode(s, encodeSlash = true) {
  let out = encodeURIComponent(String(s)).replace(/[!'()*]/g, (c) => '%' + c.charCodeAt(0).toString(16).toUpperCase());
  if (!encodeSlash) {
    out = out.replace(/%2F/g, '/');
  }
  return out;
}
const DEFAULT_SIGN_HEADERS = ['host', 'content-length', 'content-type', 'content-md5'];
function pickSignedHeaders(headers) {
  const norm = {};
  for (const [k, v] of Object.entries(headers)) {
    norm[k.toLowerCase()] = String(v).trim();
  }
  const picked = [];
  for (const key of DEFAULT_SIGN_HEADERS) {
    if (norm[key]) {
      picked.push([key, norm[key]]);
    }
  }
  for (const [key, val] of Object.entries(norm)) {
    if (key.startsWith('x-bce-') && val) {
      picked.push([key, val]);
    }
  }
  return picked;
}

const AUTH_EXPIRATION_SECONDS = 1800;

function buildAuthorization(method, p, query, headers, ak, sk) {
  const ts = new Date().toISOString().replace(/\.\d{3}Z$/, 'Z');
  const prefix = `bce-auth-v1/${ak}/${ts}/${AUTH_EXPIRATION_SECONDS}`;
  const canonicalUri = uriEncode(p, false);
  const qItems = [];
  for (const k of Object.keys(query).sort()) {
    if (k.toLowerCase() === 'authorization') {
      continue;
    }
    qItems.push(`${uriEncode(k)}=${uriEncode(query[k] ?? '')}`);
  }
  const picked = pickSignedHeaders(headers);
  const canonicalHeaders = picked
    .map(([k, v]) => `${uriEncode(k)}:${uriEncode(v)}`)
    .sort()
    .join('\n');
  const signedNames = picked
    .map(([k]) => k)
    .sort()
    .join(';');
  const canonicalRequest = [method.toUpperCase(), canonicalUri, qItems.join('&'), canonicalHeaders].join('\n');
  const signingKey = crypto.createHmac('sha256', sk).update(prefix).digest('hex');
  const signature = crypto.createHmac('sha256', signingKey).update(canonicalRequest).digest('hex');
  return `${prefix}/${signedNames}/${signature}`;
}

// ── 底层请求 ────────────────────────────────────────────────────────────────
function baseHeaders(userId, baseUrl) {
  return {
    Host: new URL(baseUrl || cfg.mktServiceBaseUrl).host,
    'X-BCE-USER-ID': userId,
    'Content-Type': 'application/json',
  };
}

async function send(method, rawPath, { params, jsonBody, extraHeaders, baseUrl } = {}) {
  const base = baseUrl || cfg.mktServiceBaseUrl;
  if (!base) {
    throw new Error('缺少 MKT_SERVICE_BASE_URL 配置');
  }
  let pathOnly = rawPath;
  const query = {};
  const qi = rawPath.indexOf('?');
  if (qi >= 0) {
    pathOnly = rawPath.slice(0, qi);
    for (const pair of rawPath.slice(qi + 1).split('&')) {
      if (!pair) {
        continue;
      }
      const eq = pair.indexOf('=');
      if (eq < 0) {
        query[pair] = '';
      } else {
        query[pair.slice(0, eq)] = pair.slice(eq + 1);
      }
    }
  }
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      query[k] = v == null ? '' : String(v);
    }
  }

  const auth = checkAuthState();
  if (!auth.logged_in) {
    throw new LoginRequiredError(auth.hint || loginGuide());
  }

  const creds = await getSts();
  const headers = baseHeaders(creds.user_id || cfg.mktServiceUserId, base);
  headers['x-bce-security-token'] = creds.session_token;
  if (extraHeaders) {
    Object.assign(headers, extraHeaders);
  }
  headers.Authorization = buildAuthorization(
    method,
    pathOnly,
    query,
    headers,
    creds.access_key_id,
    creds.secret_access_key,
  );

  const qs = new URLSearchParams(query).toString();
  const url = `${base}${pathOnly}${qs ? `?${qs}` : ''}`;
  const opts = { method, headers };
  if (jsonBody != null) {
    opts.body = JSON.stringify(jsonBody);
  }
  const resp = await fetchWithTimeout(url, opts, 10000);
  const text = await resp.text();
  if (!resp.ok) {
    throw new HttpStatusError(resp.status, text);
  }
  return text ? JSON.parse(text) : {};
}

const get = (p, params) => send('GET', p, { params });

async function getOrNull(p, params) {
  try {
    return await get(p, params);
  } catch (e) {
    if (e instanceof HttpStatusError && e.status === 404) {
      return null;
    }
    throw e;
  }
}

// ── 订单归属校验（越权防护）────────────────────────────────────────────────
// 归属键优先用 STS 的 IAM userId（跨进程/重启对同一登录稳定），拿不到再退回
// apiKey。未知归属时：写操作交后端按 IAM 身份裁决（同一用户可取消自己的单）、
// 读敏感信息保守拒绝；OWNER_STRICT=1 恢复严格。
const realOrderOwner = new Map();
function ownerStrict() {
  const v = (process.env.OWNER_STRICT || '').trim().toLowerCase();
  return ['1', 'true', 'yes', 'on'].includes(v);
}

async function ownerKey(apiKey) {
  try {
    const creds = await getSts();
    if (creds && creds.user_id) {
      return `iam:${creds.user_id}`;
    }
  } catch {
    /* 未登录等：退回 apiKey */
  }
  return `key:${apiKey}`;
}

async function rememberOrderOwner(orderId, apiKey) {
  realOrderOwner.set(orderId, await ownerKey(apiKey));
}

async function checkOrderOwner(orderId, apiKey, { write, sensitive = false } = {}) {
  const key = await ownerKey(apiKey);
  const owner = realOrderOwner.get(orderId);
  if (owner != null) {
    if (owner === key) {
      return true;
    }
    if (write) {
      throw new PermissionDeniedError('无权操作此订单（该订单属于其他用户）');
    }
    return false;
  }
  if (ownerStrict()) {
    if (write) {
      throw new PermissionDeniedError('无权操作此订单（严格模式：归属未记录）');
    }
    return false;
  }
  if (write) {
    return true;
  } // 交后端按 IAM 身份裁决
  return !sensitive; // 读敏感信息保守拒绝
}

function splitSku(s) {
  const i = (s || '').indexOf(':');
  return i < 0 ? [s || '', ''] : [s.slice(0, i), s.slice(i + 1)];
}

// 从 categoryLink（样例 https://market.baidu.com/list/0?cid=0）解析出 cid，
// 供后续调用复用；解析不出时返回 null。
function extractCidFromCategoryLink(categoryLink) {
  if (!categoryLink) {
    return null;
  }
  try {
    return new URL(categoryLink).searchParams.get('cid');
  } catch {
    return null;
  }
}

// ── 业务能力（对外导出的语义接口）──────────────────────────────────────────
export async function searchProducts({
  keyword,
  category,
  deliveryType,
  minPrice,
  maxPrice,
  cid = 0,
  page = 1,
  pageSize = 10,
} = {}) {
  const params = { pageNo: page, pageSize };
  if (keyword) {
    params.keyword = keyword;
  }
  if (category) {
    params.keyword = keyword ? `${keyword} ${category}` : category;
  }
  if (deliveryType) {
    params.deliveryMethods = deliveryType;
  }
  if (minPrice != null) {
    params.priceFrom = String(minPrice);
  }
  if (maxPrice != null) {
    params.priceTo = String(maxPrice);
  }
  // cid 作为路径段（默认 0）；后续调用可传入上一次响应 categoryLink 解析出的 cid。
  // 搜索走独立域名 MARKET_WEB_BASE_URL（如 https://market.baidu.com），仍 bce-auth-v1 签名。
  const base = cfg.marketWebBaseUrl;
  if (!base) {
    throw new Error('缺少商品搜索接口地址配置：请设置环境变量 MARKET_WEB_BASE_URL（如 https://market.baidu.com）');
  }
  const resp = await send('GET', `/api/market/web/list/${cid}/products`, { params, baseUrl: base });
  // 响应为 { success, status, result: { result: [...], totalCount, categoryLink } }
  const raw = resp?.result && !Array.isArray(resp.result) ? resp.result : resp;
  const products = (raw.result || []).map((p) => ({
    product_id: p.pid,
    name: p.title,
    price: p.price,
    unit: p.timeUnit,
    provider: p.vendorName,
  }));
  return {
    total: raw.totalCount ?? products.length,
    page,
    page_size: pageSize,
    cid: extractCidFromCategoryLink(raw.categoryLink) ?? String(cid),
    category_link: raw.categoryLink ?? null,
    products,
  };
}

export async function getProduct(productId) {
  // 详情与搜索同走 MARKET_WEB_BASE_URL 域名，仍 bce-auth-v1 签名。
  const base = cfg.marketWebBaseUrl;
  if (!base) {
    throw new Error('缺少商品详情接口地址配置：请设置环境变量 MARKET_WEB_BASE_URL（如 https://market.baidu.com）');
  }
  let resp;
  try {
    resp = await send('GET', `/api/market/web/product/${productId}/detail`, { baseUrl: base });
  } catch (e) {
    if (e instanceof HttpStatusError && e.status === 404) {
      return null;
    }
    throw e;
  }
  // 响应为 { success, status, result: { errCode, product: {...} } }
  const raw = resp?.result && typeof resp.result === 'object' ? resp.result : resp;
  if (raw == null || raw.errCode) {
    return null;
  }
  const product = raw.product || {};
  const info = product.productInfo || {};
  if (!info.pid) {
    return null;
  }
  const crumbs = product.crumbInfo || [];
  const skus = [];
  let totalStock = 0;
    let hasUnlimited = false;
  for (const pkg of info.priceInfo || []) {
    for (const period of pkg.periods || []) {
      const inv = period.inventory ?? 0;
      let inStock;
      if (inv === -1) {
        hasUnlimited = true;
        inStock = true;
      } else {
        totalStock += Math.max(inv, 0);
        inStock = inv > 0;
      }
      const periods = pkg.periods || [];
      const pn = period.periodName || '';
      skus.push({
        sku_id: `${pkg.packageId}:${period.periodId || ''}`,
        name: periods.length > 1 && pn ? `${pkg.packageName} - ${pn}` : pkg.packageName || pn,
        price: Number(period.price || 0),
        in_stock: inStock,
      });
    }
  }
  return {
    product_id: info.pid,
    name: info.title,
    category: crumbs.length ? crumbs[crumbs.length - 1].name : null,
    delivery_type: info.deliveryMethod,
    description: info.digest,
    provider: (product.vendorInfo || {}).vendorName,
    stock: hasUnlimited ? -1 : totalStock,
    skus,
  };
}

export function buildPayUrl(bceOrderId) {
  if (!cfg.cashierBase) {
    throw new Error(
      `缺少收银台地址配置：请在环境变量设置 CASHIER_BASE_${IAM_ENV.toUpperCase()}（或通用 CASHIER_BASE）`,
    );
  }
  return `${cfg.cashierBase}/finance/#/finance/pay~orderId=${bceOrderId}`;
}

async function fillPrices(items) {
  const cache = new Map();
  for (const it of items) {
    if (it.unit_price != null) {
      continue;
    }
    if (!cache.has(it.product_id)) {
      cache.set(it.product_id, await getProduct(it.product_id));
    }
    const product = cache.get(it.product_id);
    const sku = (product?.skus || []).find((s) => s.sku_id === it.sku_id);
    if (!product || !sku) {
      throw new Error(`无法确定商品价格：product_id=${it.product_id} sku_id=${it.sku_id}`);
    }
    it.unit_price = sku.price;
  }
  return items;
}

export async function createOrder({ items, apiKey }) {
  items = await fillPrices(items);
  const body = {
    orderInitRequestList: items.map((it) => {
      const [packageId, periodId] = splitSku(it.sku_id);
      return {
        productId: it.product_id,
        packageId,
        periodId,
        price: String(it.unit_price ?? 0),
        purchaseNum: it.quantity ?? 1,
        from: 'skill-cli',
      };
    }),
    isJointMembership: false,
  };
  const raw = await send('POST', '/v1/order?batchNew', {
    jsonBody: body,
    extraHeaders: { RequestSource: 'console', 'x-bce-request-id': crypto.randomUUID() },
  });
  const bceOrderId = (raw.bceOrderIds || [raw.bceOrderId])[0] || null;
  if (bceOrderId) {
    await rememberOrderOwner(bceOrderId, apiKey);
  }
  const total = items.reduce((s, i) => s + Number(i.unit_price || 0) * (i.quantity || 1), 0);
  return {
    order_id: bceOrderId,
    status: 'init',
    total_amount: total,
    pay_url: bceOrderId ? buildPayUrl(bceOrderId) : null,
  };
}

export async function getPaymentInfo(orderId, apiKey) {
  if (!(await checkOrderOwner(orderId, apiKey, { write: false }))) {
    return null;
  }
  const raw = await getOrNull(`/v1/order/${orderId}`);
  if (raw == null) {
    return null;
  }
  const order = raw.data || raw;
  if (!order) {
    return null;
  }
  const amount = Number(order.bcePrice || order.price || 0);
  return { order_id: orderId, status: String(order.orderStatus || 'INIT').toLowerCase(), payable_amount: amount };
}

export async function cancelOrder(orderId, apiKey) {
  await checkOrderOwner(orderId, apiKey, { write: true });
  await send('PUT', `/v1/order/cancel/${orderId}`, { jsonBody: {} });
  return { order_id: orderId, status: 'CANCELLED' };
}

export async function getRecord(recordId, apiKey) {
  const raw = await getOrNull(`/v1/record/${recordId}`);
  if (raw == null) {
    return null;
  }
  const rec = raw.data || raw;
  if (!rec) {
    return null;
  }
  if (!(await checkOrderOwner(rec.bceOrderId || '', apiKey, { write: false, sensitive: true }))) {
    return null;
  }
  return {
    record_id: recordId,
    order_id: rec.bceOrderId,
    product_name: rec.productName,
    delivery_type: rec.deliveryMethod || rec.deliveryType,
    record_status: rec.recordStatus || rec.status || 'PROCESSING',
    delivery_info: rec.deliveryInfo || {},
  };
}
