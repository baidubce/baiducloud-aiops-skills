const METRICS_SKILL_ID = 'mkt-service';
function metricsFilePath() {
  const override = process.env.CLOUDMARKET_METRICS_FILE;
  if (override) {
    return override.startsWith('~') ? path.join(os.homedir(), override.slice(1)) : override;
  }
  return path.join(os.homedir(), '.config', 'cloudmarket', 'metrics.json');
}

export function metricsLocalDate(d = new Date()) {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}

function metricsLoad() {
  try {
    const f = metricsFilePath();
    if (!fs.existsSync(f)) {
      return { version: 2, days: {} };
    }
    const data = JSON.parse(fs.readFileSync(f, 'utf-8'));
    if (!data || typeof data !== 'object' || data.version !== 2 || typeof data.days !== 'object') {
      return { version: 2, days: {} };
    }
    return { version: 2, days: data.days || {} };
  } catch {
    return { version: 2, days: {} };
  }
}

function metricsSave(store) {
  try {
    const f = metricsFilePath();
    fs.mkdirSync(path.dirname(f), { recursive: true });
    const tmp = `${f}.${crypto.randomBytes(4).toString('hex')}.tmp`;
    fs.writeFileSync(tmp, JSON.stringify(store, null, 2), { encoding: 'utf-8', mode: 0o600 });
    fs.renameSync(tmp, f);
  } catch {
    /* ignore */
  }
}

function metricsDayAccount(store, date, accountId) {
  const key = accountId == null ? '' : String(accountId);
  if (!store.days[date]) {
    store.days[date] = {};
  }
  if (!store.days[date][key]) {
    store.days[date][key] = { logins: 0, commands: {} };
  }
  const b = store.days[date][key];
  if (typeof b.logins !== 'number') {
    b.logins = 0;
  }
  if (!b.commands || typeof b.commands !== 'object') {
    b.commands = {};
  }
  return b;
}

// 记录一次命令调用：feature=命令功能名；accountId=当时 active 账号（可空）。
export function recordCall(feature, accountId = null, date = metricsLocalDate()) {
  try {
    const f = String(feature || 'unknown');
    const s = metricsLoad();
    const b = metricsDayAccount(s, date, accountId);
    b.commands[f] = (Number(b.commands[f]) || 0) + 1;
    metricsSave(s);
  } catch {
    /* ignore */
  }
}

// 记录一次"真正新登录"：按账号累加当日 logins（免登/切账号不调用）。
function recordLoginMetric(accountId, date = metricsLocalDate()) {
  try {
    if (!accountId) {
      return;
    }
    const s = metricsLoad();
    const b = metricsDayAccount(s, date, accountId);
    b.logins += 1;
    metricsSave(s);
  } catch {
    /* ignore */
  }
}

export function metricsSummary(date = metricsLocalDate()) {
  const s = metricsLoad();
  const day = s.days[date] || {};
  let totalCalls = 0;
  let loginAccounts = 0;
  const accounts = {};
  for (const [acct, b] of Object.entries(day)) {
    const commands = b.commands || {};
    const calls = Object.values(commands).reduce((a, c) => a + (Number(c) || 0), 0);
    const logins = Number(b.logins) || 0;
    totalCalls += calls;
    if (logins > 0) {
      loginAccounts += 1;
    }
    accounts[acct || '(anonymous)'] = { logins, calls, commands };
  }
  return {
    date,
    metrics_file: metricsFilePath(),
    total_calls: totalCalls,
    login_account_count: loginAccounts,
    accounts,
  };
}

// 构建上报 records（增量）：每个 (account, recordType, skillName) 一条，
// usageCount = 本地累计 − 已成功上报数（bucket.reported），≤0 的不报。
//   CALL  —— skillName=命令名，usageCount=调用次数
//   LOGIN —— skillName='login'，usageCount=新登录次数
// 只构建有真实 account_id 的桶；传 onlyAccountId 只构建该账号；date 为空则遍历所有日期。
function metricsBuildItems(date = null, skillId = METRICS_SKILL_ID, onlyAccountId = null) {
  const s = metricsLoad();
  const dates = date ? [date] : Object.keys(s.days).sort();
  const items = [];
  for (const d of dates) {
    for (const [acct, b] of Object.entries(s.days[d] || {})) {
      if (!acct || (onlyAccountId != null && acct !== String(onlyAccountId))) {
        continue;
      }
      const reported = (b.reported && typeof b.reported === 'object' && b.reported) || {};
      const push = (recordType, skillName, total) => {
        const usageCount = (Number(total) || 0) - (Number(reported[`${recordType}:${skillName}`]) || 0);
        if (usageCount > 0) {
          items.push({ statDate: d, accountId: acct, skillId, skillName, recordType, usageCount });
        }
      };
      for (const [feature, count] of Object.entries(b.commands || {})) {
        push('CALL', feature, count);
      }
      push('LOGIN', 'login', b.logins);
    }
  }
  return items;
}

// 上报成功后把本次 usageCount 累加进 bucket.reported，下次只报新增部分。
function metricsMarkReported(records) {
  try {
    const s = metricsLoad();
    for (const r of records) {
      const b = metricsDayAccount(s, r.statDate, r.accountId);
      if (!b.reported || typeof b.reported !== 'object') {
        b.reported = {};
      }
      const k = `${r.recordType}:${r.skillName}`;
      b.reported[k] = (Number(b.reported[k]) || 0) + r.usageCount;
    }
    metricsSave(s);
  } catch {
    /* ignore */
  }
}

// 上报到后端 /v1/skill/usage/report（bce-auth-v1 签名，走本服务层 send）。后端按增量累加。
// 只上报当前登录账号的记录：签名身份就是当前账号，其他账号的记录留在本地，
// 等该账号登录后再报，避免以 A 的身份上报 B 的数据。date 为空则补报所有日期的未报增量。
export async function reportUsage(date = null, { skillId } = {}) {
  const accountId = checkAuthState().account_id;
  if (!accountId) {
    throw new LoginRequiredError(loginGuide());
  }
  const records = metricsBuildItems(date, skillId || METRICS_SKILL_ID, accountId);
  if (!records.length) {
    return { reported: false, reason: '当前账号无未上报记录', date, account_id: accountId, count: 0 };
  }
  const raw = await send('POST', '/v1/skill/usage/report', {
    jsonBody: { records },
    extraHeaders: { RequestSource: 'console', 'x-bce-request-id': crypto.randomUUID() },
    // 上报可单独指定后端；未设置时与其他接口一样走 MKT_SERVICE_BASE_URL。
    baseUrl: cfg.usageReportBaseUrl || undefined,
  });
  metricsMarkReported(records);
  return { reported: true, date, account_id: accountId, count: records.length, response: raw ?? null };
}

// 命令结束后自动上报（best-effort）：未登录、未配置后端或 CLOUDMARKET_AUTO_REPORT=0 时跳过；
// 任何失败都吞掉，未报的增量留在本地，下次命令再补报。
export async function autoReportUsage() {
  try {
    const v = (process.env.CLOUDMARKET_AUTO_REPORT || '').trim().toLowerCase();
    if (['0', 'false', 'no', 'off'].includes(v)) {
      return;
    }
    if (!(cfg.usageReportBaseUrl || cfg.mktServiceBaseUrl) || !checkAuthState().logged_in) {
      return;
    }
    await reportUsage(null);
  } catch {
    /* ignore：上报失败绝不影响命令结果 */
  }
}

export function checkAuthState() {
  const now = Date.now() / 1000;
  const state = {
    env: IAM_ENV,
    token_file: CLI_TOKEN_FILE,
    token_present: false,
    state_readable: true,
    logged_in: false,
    credentials_expired: null,
    account_id: null,
    username: null,
    hint: null,
  };
  if (fs.existsSync(CLI_TOKEN_FILE) && fs.statSync(CLI_TOKEN_FILE).isFile()) {
    state.token_present = true;
    let data = null;
    try {
      data = JSON.parse(fs.readFileSync(CLI_TOKEN_FILE, 'utf-8'));
    } catch {
      state.state_readable = false;
    }
    if (data && typeof data === 'object') {
      const exp = data.refresh_token_expires_at;
      if (typeof exp === 'number') {
        state.credentials_expired = exp <= now;
      }
      state.logged_in = Boolean(data.refresh_token) && state.credentials_expired !== true;
      const identity = recordIdentity(data);
      state.account_id = identity.account_id;
      state.username = identity.username;
    }
  }
  if (!state.logged_in) {
    state.hint = state.state_readable ? loginGuide() : `凭证文件损坏，请重新登录（${CLI_TOKEN_FILE}）`;
  }
  return state;
}

// ── 主动发起登录（IAM OAuth Authorization Code + PKCE，浏览器）────────────────
// 自包含：仅用 Node 内建 http/child_process/crypto。做一次完整授权码流程，
// 与 refresh_token 是否过期无关——因此 refresh_token 失效后同样可用它重新登录。
function b64urlNoPad(buf) {
  return buf.toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
}

function genPkce() {
  const verifier = b64urlNoPad(crypto.randomBytes(64)).slice(0, 128);
  const challenge = b64urlNoPad(crypto.createHash('sha256').update(verifier).digest());
  return { verifier, challenge };
}

// 解码 JWT payload（仅取 claim，不校验签名）。失败返回 null。
function decodeJwtPayload(jwt) {
  try {
    const parts = String(jwt || '').split('.');
    if (parts.length !== 3) {
      return null;
    }
    const json = Buffer.from(parts[1].replace(/-/g, '+').replace(/_/g, '/'), 'base64').toString('utf-8');
    return JSON.parse(json);
  } catch {
    return null;
  }
}

// 登录人标识：优先持久化字段，回退解码 id_token（兼容旧记录）。
function recordIdentity(record) {
  if (!record || typeof record !== 'object') {
    return { account_id: null, username: null };
  }
  let accountId = record.account_id ?? null;
  let username = record.username ?? null;
  if (accountId == null || username == null) {
    const p = decodeJwtPayload(record.id_token) || {};
    if (accountId == null) {
      accountId = p.account_id ?? null;
    }
    if (username == null) {
      username = p.username ?? null;
    }
  }
  return { account_id: accountId, username };
}

// ---- 多账号隔离：按 env + account_id 分文件存储（与 src/tokenStore 同构）----
function sanitizeAccountId(id) {
  return String(id).replace(/[^A-Za-z0-9_.-]/g, '_');
}

function accountTokenFile(env, accountId) {
  const active = tokenFilePath(env);
  const safe = sanitizeAccountId(accountId);
  const slash = Math.max(active.lastIndexOf('/'), active.lastIndexOf('\\'));
  const dot = active.lastIndexOf('.');
  if (dot > slash) {
    return `${active.slice(0, dot)}__${safe}${active.slice(dot)}`;
  }
  return `${active}__${safe}`;
}

function safeLoadFile(file) {
  try {
    if (fs.existsSync(file) && fs.statSync(file).isFile()) {
      return JSON.parse(fs.readFileSync(file, 'utf-8'));
    }
  } catch {
    /* ignore */
  }
  return null;
}

function recordNotExpired(record) {
  if (!record || typeof record !== 'object') {
    return false;
  }
  const now = Date.now() / 1000;
  return (
    Boolean(record.refresh_token) &&
    typeof record.refresh_token_expires_at === 'number' &&
    record.refresh_token_expires_at > now
  );
}

// 写登录记录（多账号安全）：先归档"当前 active 且属不同账号"的旧记录防覆盖，
// 再写本账号归档，最后设为 active（运行期固定读 active）。
function persistLoginRecord(env, record) {
  const activePath = tokenFilePath(env);
  const prev = safeLoadFile(activePath);
  const prevId = recordIdentity(prev).account_id;
  if (prevId && record.account_id && String(prevId) !== String(record.account_id)) {
    saveTokens(prev, accountTokenFile(env, prevId));
  }
  if (record.account_id) {
    saveTokens(record, accountTokenFile(env, record.account_id));
  }
  saveTokens(record, activePath);
}

// 登录决策：skip（active 已满足）/ promote（归档命中可提升，免浏览器）/ login（需授权）。
function resolveLoginPlan(env, wantAccountId = null) {
  const active = safeLoadFile(tokenFilePath(env));
  const activeIdentity = recordIdentity(active);
  const activeValid = recordNotExpired(active);
  if (wantAccountId == null) {
    if (activeValid) {
      return { action: 'skip', record: active, identity: activeIdentity };
    }
    return { action: 'login', record: null, identity: { account_id: null, username: null } };
  }
  if (activeValid && String(activeIdentity.account_id) === String(wantAccountId)) {
    return { action: 'skip', record: active, identity: activeIdentity };
  }
  const arch = safeLoadFile(accountTokenFile(env, wantAccountId));
  const archIdentity = recordIdentity(arch);
  if (recordNotExpired(arch) && String(archIdentity.account_id) === String(wantAccountId)) {
    return { action: 'promote', record: arch, identity: archIdentity };
  }
  return { action: 'login', record: null, identity: { account_id: null, username: null } };
}

